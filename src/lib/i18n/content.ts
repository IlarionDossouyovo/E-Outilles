const LOCALE_INDEX: Record<Exclude<Locale, 'fr'>, number> = { en: 0, es: 1, pt: 2 }

/**
 * Translates a catalogue string for the active locale. Returns the original
 * French text when the locale is `fr` or when no translation is known.
 */
export function localizeText(value: string | null | undefined, locale: Locale): string {
  if (!value) return ''
  if (locale === FR) return value
  const row = TABLE[value]
  if (!row) return value
  return row[LOCALE_INDEX[locale]] ?? value
}

export function localizeList(values: readonly string[], locale: Locale): string[] {
  return values.map((v) => localizeText(v, locale))
}
